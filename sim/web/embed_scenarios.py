#!/usr/bin/env python3
"""Packs the sample forecasts into a C header so the emulator needs no files."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SC = os.path.join(HERE, "..", "scenarios")
ORDER = [("oct_morning", "Fri morning"),
         ("thu_evening", "Thu evening"),
         ("rainy_afternoon", "Rainy"),
         ("snow_morning", "Snow day"),
         ("summer_hot", "Hot summer")]
with open(os.path.join(HERE, "scenarios_data.h"), "w") as f:
    f.write("/* Generated by embed_scenarios.py */\n#pragma once\n")
    f.write("typedef struct { const char *name; const char *json; } scenario_t;\n")
    f.write("static const scenario_t SCENARIOS[] = {\n")
    for key, label in ORDER:
        txt = json.dumps(json.load(open(os.path.join(SC, key + ".json"))), separators=(",", ":"))
        f.write(f'    {{"{label}",\n')
        for i in range(0, len(txt), 4000):
            f.write('        "' + txt[i:i + 4000].replace("\\", "\\\\").replace('"', '\\"') + '"\n')
        f.write("    },\n")
    f.write("};\n#define NUM_SCENARIOS ((int)(sizeof(SCENARIOS) / sizeof(SCENARIOS[0])))\n")
print("scenarios_data.h written")
